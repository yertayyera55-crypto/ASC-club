create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  display_name text;
  given_name text;
  family_name text;
  initial_role public.app_role;
  initial_status public.profile_status;
begin
  display_name := coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', '');
  given_name := coalesce(nullif(new.raw_user_meta_data ->> 'given_name', ''), split_part(display_name, ' ', 1), '');
  family_name := coalesce(
    nullif(new.raw_user_meta_data ->> 'family_name', ''),
    nullif(trim(substring(display_name from length(split_part(display_name, ' ', 1)) + 1)), ''),
    ''
  );

  if lower(coalesce(new.email, '')) = 'yertay.yera55@gmail.com' then
    initial_role := 'admin';
    initial_status := 'active';
  else
    initial_role := 'member';
    initial_status := 'pending';
  end if;

  insert into public.profiles (id, first_name, last_name, role, status)
  values (new.id, given_name, family_name, initial_role, initial_status)
  on conflict (id) do nothing;

  insert into public.member_contacts (user_id, email)
  values (new.id, coalesce(new.email, ''))
  on conflict (user_id) do update set email = excluded.email;

  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function private.handle_new_user();

