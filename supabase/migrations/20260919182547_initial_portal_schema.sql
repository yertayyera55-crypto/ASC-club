create or replace function private.is_active_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid()) and status = 'active'
  );
$$;

create or replace function private.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and status = 'active'
      and role in ('organizer', 'admin')
  );
$$;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and status = 'active'
      and role = 'admin'
  );
$$;

revoke all on function private.is_active_member() from public, anon;
revoke all on function private.is_staff() from public, anon;
revoke all on function private.is_admin() from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.is_active_member() to authenticated;
grant execute on function private.is_staff() to authenticated;
grant execute on function private.is_admin() to authenticated;

create or replace function private.refresh_event_attendee_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event_id uuid;
begin
  target_event_id := coalesce(new.event_id, old.event_id);
  update public.events
  set attendee_count = (
    select count(*)::integer
    from public.event_rsvps
    where event_id = target_event_id
  )
  where id = target_event_id;
  return coalesce(new, old);
end;
$$;

revoke all on function private.refresh_event_attendee_count() from public, anon, authenticated;

create trigger event_rsvps_refresh_count
after insert or delete on public.event_rsvps
for each row execute function private.refresh_event_attendee_count();

