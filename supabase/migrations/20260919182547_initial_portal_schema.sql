create type public.app_role as enum ('member', 'organizer', 'admin');
create type public.profile_status as enum ('pending', 'active', 'suspended');

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  member_number bigint generated by default as identity (start with 1001),
  first_name text not null default '',
  last_name text not null default '',
  grade smallint check (grade between 7 and 12),
  direction text check (direction in ('Machine Learning', 'Arduino', 'Both', 'Not sure')),
  level text check (level in ('Beginner', 'Intermediate', 'Advanced')),
  skills text[] not null default '{}',
  competition_interest boolean not null default false,
  role public.app_role not null default 'member',
  status public.profile_status not null default 'pending',
  bio text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_member_number_unique unique (member_number)
);

create table public.member_contacts (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  email text not null,
  whatsapp text not null default '',
  updated_at timestamptz not null default now()
);

create table public.events (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  location text not null,
  description text not null default '',
  attendee_count integer not null default 0 check (attendee_count >= 0),
  status text not null default 'upcoming' check (status in ('upcoming', 'past', 'cancelled')),
  category text not null default 'Club event',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint events_time_order check (ends_at > starts_at)
);

create table public.announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  body text not null,
  published_at timestamptz not null default now(),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.event_rsvps (
  event_id uuid not null references public.events(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (event_id, user_id)
);

create index profiles_status_idx on public.profiles(status);
create index profiles_role_idx on public.profiles(role);
create index events_starts_at_idx on public.events(starts_at);
create index announcements_published_at_idx on public.announcements(published_at desc);
create index event_rsvps_user_id_idx on public.event_rsvps(user_id);

